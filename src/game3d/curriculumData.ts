export function getBabsByGrade(grade: GradeNumber): BabDefinition[] {
  return CURRICULUM_BABS.filter((b) => b.grade === grade).sort(
    (a, b) => a.babOrder - b.babOrder
  );
}

export function getBabDefinition(grade: GradeNumber, babOrder: 1 | 2 | 3 | 4): BabDefinition {
  return (
    CURRICULUM_BABS.find((b) => b.grade === grade && b.babOrder === babOrder) ??
    CURRICULUM_BABS[0]
  );
}

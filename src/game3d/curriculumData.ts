export type { GradeNumber };

export function getBabId(grade: GradeNumber, babOrder: 1 | 2 | 3 | 4): string {
  return `k${grade}-b${babOrder}`;
}

export function isBabUnlocked(
  progress: PlayerProgress3D,
  grade: GradeNumber,
  babOrder: 1 | 2 | 3 | 4
): boolean {
  if (babOrder === 1) return true;
  const prevBabId = getBabId(grade, (babOrder - 1) as 1 | 2 | 3 | 4);
  return progress.completedBabs.includes(prevBabId);
}

export function getGradeCompletedCount(progress: PlayerProgress3D, grade: GradeNumber): number {
  let count = 0;
  for (let b = 1 as 1 | 2 | 3 | 4; b <= 4; b = (b + 1) as 1 | 2 | 3 | 4) {
    if (progress.completedBabs.includes(getBabId(grade, b))) count++;
  }
  return count;
}


export function getAgamaChaptersForGrade(
  grade: GradeNumber,
  religion: ReligionId
): SubjectChapter[] {
  const band: GradeBand = grade <= 2 ? '1-2' : grade <= 4 ? '3-4' : '5-6';
  return AGAMA_TEMPLATES.filter(
    (item) => item.religion === religion && item.band === band
  ).map(({ religion: _rel, band: _band, ...rest }) => ({
    ...rest,
    id: `g${grade}-agama-${religion}-${rest.chapterNumber}`,
    grade,
  }));
}

